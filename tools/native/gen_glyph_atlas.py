#!/usr/bin/env python3
"""Generates the bitmap glyph atlas used by the native renderer.

The native binary has no font library dependency: the exact glyph coverage
masks used by the Python renderer (same DejaVu fonts, same sizes) are baked
into ``glyph_atlas.c``.  Re-run this script if you change the label fonts::

    python3 tools/native/gen_glyph_atlas.py
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))

# (variant id, pixel size, bold) - order must match monomesh.h
VARIANTS = [
    (0, 14, True),
    (1, 12, True),
    (2, 10, True),
    (3, 9, False),
]

FIRST_CHAR = 32
LAST_CHAR = 255

FONT_CANDIDATES = {
    True: [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
        "/usr/share/fonts/truetype/ubuntu/Ubuntu-B.ttf",
    ],
    False: [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
        "/usr/share/fonts/truetype/ubuntu/Ubuntu-R.ttf",
    ],
}


def load_font(size, bold):
    for path in FONT_CANDIDATES[bold]:
        if os.path.exists(path):
            return ImageFont.truetype(path, size), path
    raise SystemExit("[!] Nessun font TTF trovato (serve DejaVu/Liberation/Ubuntu)")


def render_glyph(font, code):
    """Returns (left, top, width, height, advance, coverage bytes)."""
    ch = chr(code)
    try:
        bbox = font.getbbox(ch)
    except Exception:
        return None
    # 26.6 fixed point: keeps sub-pixel pen accumulation like Pillow does
    advance = int(round(font.getlength(ch) * 64.0))
    left, top, right, bottom = bbox
    w = max(0, right - left)
    h = max(0, bottom - top)
    if w == 0 or h == 0:
        return (left, top, 0, 0, advance, b"")
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    # bbox is relative to the text origin; shift the glyph so that its own
    # bounding box starts at (0, 0).
    draw.text((-left, -top), ch, fill=255, font=font)
    data = mask.tobytes()
    return (left, top, w, h, advance, data)


def main():
    blob = bytearray()
    index = []  # (variant, offset, length) for each codepoint entry

    for variant, size, bold in VARIANTS:
        font, path = load_font(size, bold)
        print(f"[*] variant {variant}: {os.path.basename(path)} @ {size}px bold={bold}")
        for code in range(FIRST_CHAR, LAST_CHAR + 1):
            glyph = render_glyph(font, code)
            entry_off = len(blob)
            if glyph is None:
                blob += bytes((0, 0, 0, 0, 0, 0))
            else:
                left, top, w, h, advance, data = glyph
                if w > 255 or h > 255:
                    raise SystemExit(f"[!] glyph too large: {code}")
                adv = max(-32768, min(32767, advance))
                blob += bytes((w, h, left & 0xFF, top & 0xFF))
                blob += (adv & 0xFFFF).to_bytes(2, "little")
                blob += data
            index.append((variant, entry_off, len(blob) - entry_off))

    # Emit the C source
    out_c = os.path.join(HERE, "libmapcore", "glyph_atlas.c")
    with open(out_c, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/native/gen_glyph_atlas.py - do not edit. */\n")
        f.write("#include \"glyph_atlas.h\"\n\n")
        f.write(f"const unsigned int monomesh_glyph_atlas_len = {len(blob)}u;\n")
        f.write("const unsigned char monomesh_glyph_atlas[] = {\n")
        for i in range(0, len(blob), 16):
            chunk = blob[i:i + 16]
            f.write("    " + "".join(f"0x{b:02x}," for b in chunk) + "\n")
        f.write("};\n")

    out_h = os.path.join(HERE, "libmapcore", "glyph_atlas.h")
    with open(out_h, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/native/gen_glyph_atlas.py - do not edit. */\n")
        f.write("#ifndef MONOMESH_GLYPH_ATLAS_H\n#define MONOMESH_GLYPH_ATLAS_H\n\n")
        f.write("#define MONOMESH_ATLAS_VARIANTS %d\n" % len(VARIANTS))
        f.write("#define MONOMESH_ATLAS_FIRST_CHAR %d\n" % FIRST_CHAR)
        f.write("#define MONOMESH_ATLAS_LAST_CHAR %d\n" % LAST_CHAR)
        f.write("extern const unsigned char monomesh_glyph_atlas[];\n")
        f.write("extern const unsigned int monomesh_glyph_atlas_len;\n\n")
        f.write("#endif\n")

    print(f"[✓] {len(blob) / 1024:.1f} KB di atlas scritti in {out_c}")


if __name__ == "__main__":
    sys.exit(main())
